#!/usr/bin/env python3
"""Regenerate the "All catalogued limits" table in README.md from fine_print/catalog.json and the
registered detectors. Usage: python3 dev/readme_table.py [--check]"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from fine_print import rules  # noqa: E402,F401
from fine_print.engine import REGISTRY  # noqa: E402

HEADING = "## All catalogued limits"
MARK = {"verified": "live, verified", "fixture": "live, fixture-only"}


def table() -> str:
    data = json.loads((ROOT / "fine_print" / "catalog.json").read_text(encoding="utf-8"))
    entries = data["entries"]
    live = sum(1 for e in entries if REGISTRY.get(e["id"]))
    lines = [HEADING, "",
             f"{len(entries)} limits of Hermes v{data['version']}; {live} have a live detector in this version, the "
             "rest are explained by `/limits explain <id>`. Generated by `dev/readme_table.py`.", "",
             "| Topic | Limit | Hermes tells | Fine Print |", "|---|---|---|---|"]
    for e in entries:
        rule = REGISTRY.get(e["id"])
        status = MARK.get(getattr(rule, "status", ""), "reference")
        title = e["title"].replace("|", "\\|")
        lines.append(f"| {e['topic']} | `{e['id']}`: {title} | {e['told']} | {status} |")
    return "\n".join(lines) + "\n"


DETECTORS = "## Detectors in this version"
TELLS = {"nobody": "nobody", "model": "the model", "user": "the user", "both": "the model and the user"}


def detectors() -> str:
    rules_ = sorted(REGISTRY.all(), key=lambda r: (r.status != "verified", r.driver, r.id))
    lines = [DETECTORS, "", "| Limit | Seen by | Hermes tells | Status |", "|---|---|---|---|"]
    for r in rules_:
        status = "verified" if r.status == "verified" else "fixture-only"
        lines.append(f"| `{r.id}` | {r.driver} driver | {TELLS.get(r.core_tells, r.core_tells)} | {status} |")
    return "\n".join(lines) + "\n"


def main() -> int:
    readme = ROOT / "README.md"
    text = updated = readme.read_text(encoding="utf-8")
    for heading, block, keep_tail in ((HEADING, table(), False), (DETECTORS, detectors(), True)):
        # the detectors section keeps its hand-written paragraphs after the generated table
        stop = r"(?=\n\*Verified\*|\n## |\Z)" if keep_tail else r"(?=\n## |\Z)"
        pattern = re.compile(re.escape(heading) + r"\n.*?" + stop, re.S)
        if not pattern.search(updated):
            print("README.md has no section", heading)
            return 1
        updated = pattern.sub(lambda _m, b=block: b.rstrip("\n") + "\n", updated, count=1)
    if "--check" in sys.argv:
        if updated != text:
            print("README.md tables are stale: run python3 dev/readme_table.py")
            return 1
        return 0
    readme.write_text(updated, encoding="utf-8")
    print("README.md tables written")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
